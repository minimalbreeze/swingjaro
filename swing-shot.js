  function findSymptoms(q, handed) {
    var t = String(q || '').trim().toLowerCase();
    if (!t) return SYMPTOMS;
    return SYMPTOMS.filter(function (s) {
      var hay = (mirror(s.label, handed) + ' ' + s.key + ' ' + mirror(s.what, handed)).toLowerCase();
      // 띄어쓰기로 나눠 하나라도 걸리면 보여준다. 짧게 쳐도 찾아지게.
      return t.split(/\s+/).some(function (w) { return w && hay.indexOf(w) >= 0; });
    });
  }

  /* ── 화면 그리기 ───────────────────────────────────────────────
   * 진단 결과(report)가 있으면 "지금 내 스윙이 이 목표와 맞는지"를 함께 보여준다.
   * 없으면 가이드만 보여준다. 지어내지 않고 잰 것만 말한다.
   */
  function esc(x) {
    return String(x).replace(/[&<>"']/g, function (c) {
      return { '&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;' }[c];
    });
  }
  // 가이드 문구에는 <b> 를 일부러 쓰므로 이스케이프하지 않는다. 전부 이 파일 안에서
  // 내가 쓴 고정 문자열이고 사용자 입력이 섞이지 않는다.
  function M(t, h) { return mirror(t, h); }

  function faultTitle(id) {
    var F = global.SwingFaults && global.SwingFaults.FAULTS[id];
    return F ? F.emoji + ' ' + F.title : id;
  }
  // 최근 분석에서 이 항목들이 실제로 잡혔는지
  function hitList(ids, report) {
    if (!report || !report.faults || !ids || !ids.length) return [];
    return report.faults.filter(function (f) { return ids.indexOf(f.faultId) >= 0; });
  }

