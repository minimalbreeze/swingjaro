/* 스윙자로 — 단계 아이콘
 *
 * 골프픽스처럼 "이 단계가 어떤 자세인지"만 알려주는 고정 그림이다.
 * 내 스윙 분석 결과를 여기 담지 않는다. 분석은 아래 진단이 하고,
 * 이 그림은 단계를 알아보게 하는 이정표 역할만 한다.
 *
 * 60 x 80 상자에 옆모습(오른손잡이가 오른쪽 볼을 보는 방향)으로 그린다.
 * 좌표는 눈으로 맞춘 값이라 해부학적 정밀도는 없다 — 알아보기가 목적이다.
 */
(function (global) {
  'use strict';

  // head:[x,y,r] spine:[[어깨],[골반]] legs:[[골반],[무릎],[발]] x2
  // arms:[[어깨],[손]] club:[[손],[클럽끝]]
  var POSE = {
    P1: {  // 어드레스 — 상체를 숙이고 클럽을 볼 뒤에
      head:[31,15,5.5], spine:[[30,24],[26,44]],
      legs:[[[26,44],[28,58],[25,73]],[[26,44],[31,58],[31,73]]],
      arms:[[30,24],[34,45]], club:[[34,45],[46,72]]
    },
    P2: {  // 테이크어웨이 — 클럽을 낮게 뒤로
      head:[31,15,5.5], spine:[[30,24],[26,44]],
      legs:[[[26,44],[28,58],[25,73]],[[26,44],[31,58],[31,73]]],
      arms:[[30,24],[22,40]], club:[[22,40],[6,50]]
    },
    P3: {  // 백스윙 — 팔이 어깨 높이
      head:[32,15,5.5], spine:[[31,24],[27,44]],
      legs:[[[27,44],[28,58],[25,73]],[[27,44],[32,58],[32,73]]],
      arms:[[31,24],[18,29]], club:[[18,29],[7,14]]
    },
    P4: {  // 톱 — 클럽이 머리 위 뒤로
      head:[33,15,5.5], spine:[[32,24],[27,44]],
      legs:[[[27,44],[28,58],[25,73]],[[27,44],[33,58],[33,73]]],
      arms:[[32,24],[22,15]], club:[[22,15],[42,9]]
    },
    P6: {  // 다운스윙 — 클럽이 내려오는 중
      head:[31,15,5.5], spine:[[30,24],[27,44]],
      legs:[[[27,44],[28,58],[25,73]],[[27,44],[32,58],[32,73]]],
      arms:[[30,24],[24,36]], club:[[24,36],[9,44]]
    },
    P7: {  // 임팩트 — 볼 자리로 돌아오고 골반은 열림
      head:[30,15,5.5], spine:[[30,24],[27,44]],
      legs:[[[27,44],[29,58],[26,73]],[[27,44],[33,58],[34,73]]],
      arms:[[30,24],[35,44]], club:[[35,44],[46,72]]
    },
    P9: {  // 팔로스루 — 클럽이 지나가며 올라감
      head:[29,15,5.5], spine:[[30,23],[28,44]],
      legs:[[[28,44],[30,58],[27,73]],[[28,44],[34,57],[36,72]]],
      arms:[[30,23],[42,30]], club:[[42,30],[53,15]]
    },
    P10: { // 피니시 — 몸을 세우고 클럽은 등 뒤로
      head:[29,14,5.5], spine:[[30,22],[29,43]],
      legs:[[[29,43],[30,58],[28,73]],[[29,43],[35,56],[38,71]]],
      arms:[[30,22],[40,15]], club:[[40,15],[20,10]]
    }
  };

  /* 단계 아이콘 하나를 SVG 문자열로. ok=true 면 초록, 아니면 빨강. */
  function icon(frameId, ok) {
    var p = POSE[frameId];
    if (!p) return '';
    var col = ok ? '#2f9e75' : '#e2574c';
    var g = [];
    function line(pts, w) {
      var d = pts.map(function (q, i) { return (i ? 'L' : 'M') + q[0] + ' ' + q[1]; }).join(' ');
      g.push('<path d="' + d + '" stroke-width="' + w + '"/>');
    }
    p.legs.forEach(function (l) { line(l, 5); });
    line(p.spine, 6);
    line(p.arms, 4.5);
    // 클럽은 몸과 구분되게 조금 가늘고 반투명하게
    g.push('<path d="M' + p.club[0][0] + ' ' + p.club[0][1] + 'L' + p.club[1][0] + ' ' + p.club[1][1] +
      '" stroke-width="2.6" opacity=".72"/>');
    g.push('<circle cx="' + p.head[0] + '" cy="' + p.head[1] + '" r="' + p.head[2] +
      '" fill="' + col + '" stroke="none"/>');
    return '<svg class="sil" viewBox="0 0 60 80" aria-hidden="true">' +
      '<g stroke="' + col + '" stroke-linecap="round" stroke-linejoin="round" fill="none">' +
      g.join('') + '</g></svg>';
  }

  global.SwingIcons = { icon: icon, POSE: POSE };
})(window);
